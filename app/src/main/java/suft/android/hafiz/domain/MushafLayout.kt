package suft.android.hafiz.domain

import java.io.InputStream

/** Page of an open Madinah mushaf: odd pages are on the right (page 1 faces page 2). */
enum class PageSide { Right, Left }

/** A third of a page's 15 lines: 1–5, 6–10, 11–15. */
enum class PageThird { Top, Middle, Bottom }

/** The six answers of «أين الآية؟»; entry order = option order of a [GameStyle.AyahPosition] question. */
enum class MushafCell(val side: PageSide, val third: PageThird) {
    RightTop(PageSide.Right, PageThird.Top),
    RightMiddle(PageSide.Right, PageThird.Middle),
    RightBottom(PageSide.Right, PageThird.Bottom),
    LeftTop(PageSide.Left, PageThird.Top),
    LeftMiddle(PageSide.Left, PageThird.Middle),
    LeftBottom(PageSide.Left, PageThird.Bottom);

    fun label(language: AppLanguage): String = when (language) {
        AppLanguage.Arabic -> when (this) {
            RightTop -> "أعلى اليمنى"
            RightMiddle -> "وسط اليمنى"
            RightBottom -> "أسفل اليمنى"
            LeftTop -> "أعلى اليسرى"
            LeftMiddle -> "وسط اليسرى"
            LeftBottom -> "أسفل اليسرى"
        }
        AppLanguage.English -> when (this) {
            RightTop -> "Top right"
            RightMiddle -> "Middle right"
            RightBottom -> "Bottom right"
            LeftTop -> "Top left"
            LeftMiddle -> "Middle left"
            LeftBottom -> "Bottom left"
        }
    }

    companion object {
        fun of(side: PageSide, third: PageThird): MushafCell = entries.first { it.side == side && it.third == third }
    }
}

/**
 * Where each ayah starts in the Madinah mushaf, for one [MushafEdition] (604 pages of 15 lines), from
 * assets/mushaf_layout_v1.txt or mushaf_layout_v2.txt (generated by tools/mushaf_layout.py). Ayahs are global
 * indices into [Quran].
 */
class MushafLayout private constructor(private val pages: ShortArray, private val lines: ByteArray) {
    /** 1-based page of the ayah's first word. */
    fun page(ayah: Int): Int = pages[ayah].toInt()

    /** 1-based line, 1–15, of the ayah's first word; surah-title and basmala lines count. */
    fun line(ayah: Int): Int = lines[ayah].toInt()

    /**
     * The part of the open mushaf the ayah starts in. Null on pages 1–2: they hold a framed text in the middle of
     * the page, so top/middle/bottom do not apply.
     */
    fun cell(ayah: Int): MushafCell? {
        val page = page(ayah)
        if (page <= FRAMED_PAGES) return null
        return MushafCell.of(
            if (page % 2 == 1) PageSide.Right else PageSide.Left,
            PageThird.entries[(line(ayah) - 1) / LINES_PER_THIRD],
        )
    }

    companion object {
        const val PAGE_COUNT = 604
        const val LINES_PER_PAGE = 15
        private const val LINES_PER_THIRD = 5
        private const val FRAMED_PAGES = 2
        private val WHITESPACE = Regex("\\s+")

        /** Lines `surah:ayah page line`, one per ayah in mushaf order; `#` comments and blank lines are skipped. */
        fun parse(input: InputStream, quran: Quran): MushafLayout {
            val pages = ShortArray(quran.ayahCount)
            val lines = ByteArray(quran.ayahCount)
            var count = 0
            input.bufferedReader().useLines { all ->
                all.forEachIndexed { i, raw ->
                    val line = raw.trim()
                    if (line.isEmpty() || line.startsWith('#')) return@forEachIndexed
                    val n = i + 1
                    val parts = line.split(WHITESPACE)
                    require(parts.size == 3 && count < quran.ayahCount) { "mushaf layout line $n: $line" }
                    val surah = quran.surahOf(count)
                    require(parts[0] == "${surah.number}:${quran.ayahNumberInSurah(count)}") { "mushaf layout line $n: $line" }
                    val page = parts[1].toIntOrNull()
                    val lineNumber = parts[2].toIntOrNull()
                    require(page != null && page in 1..PAGE_COUNT && lineNumber != null && lineNumber in 1..LINES_PER_PAGE) {
                        "mushaf layout line $n: $line"
                    }
                    pages[count] = page.toShort()
                    lines[count] = lineNumber.toByte()
                    count++
                }
            }
            require(count == quran.ayahCount) { "mushaf layout: $count ayahs, expected ${quran.ayahCount}" }
            return MushafLayout(pages, lines)
        }
    }
}
