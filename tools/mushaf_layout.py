#!/usr/bin/env python3
"""Regenerates app/src/main/assets/mushaf_layout_v1.txt and mushaf_layout_v2.txt: where each ayah starts in the Madinah mushaf.

Source: quran.com API v4 (https://api.quran.com/api/v4), verses by page with word fields v1_page, line_v1, v2_page
and line_v2. The two layouts are the 1405H print (KFGQPC v1) and the 1421H print (KFGQPC v2); both have 604 pages
of 15 lines. An ayah starts where its first word is; line numbers count the surah-title and basmala lines.
Only page and line are kept, never the API's text.
Every ayah of each edition is checked against the bundled Tanzil text: same 6236 references, page in 1..604,
line in 1..15, pages never decreasing in mushaf order. Both editions are validated before either file is
written, so any failure aborts without writing.

Usage: python3 tools/mushaf_layout.py [--out-dir DIR]      (or: mise run mushaf-layout)
"""
import argparse
import json
import sys
import time
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
QURAN_XML = ROOT / "app/src/main/assets/quran_simple.xml"
DEFAULT_OUT_DIR = ROOT / "app/src/main/assets"
URL = (
    "https://api.quran.com/api/v4/verses/by_page/{}?words=true"
    "&word_fields=v1_page,line_v1,v2_page,line_v2&per_page=50&page={}"
)
PAGES = 604
LINES = 15
ATTEMPTS = 4
# edition -> (print description, API fields); the edition's file is mushaf_layout_<edition>.txt
EDITIONS = {
    "v1": ("1405H print (KFGQPC v1: 604 pages of 15 lines)", "v1_page and line_v1"),
    "v2": ("1421H print (KFGQPC v2: 604 pages of 15 lines)", "v2_page and line_v2"),
}
HEADER = """\
# Mushaf layout: where each ayah starts in the Madinah mushaf, {print}.
# Source: quran.com API v4 (https://api.quran.com/api/v4), fields {fields} of each ayah's first word.
# Generated by tools/mushaf_layout.py (mise run mushaf-layout); do not edit by hand.
# Format: <surah>:<ayah> <page 1-604> <line 1-15, counting surah-title and basmala lines>
"""


def load_refs():
    """Every `surah:ayah` of the Tanzil text, in mushaf order."""
    refs = [f"{s.get('index')}:{a.get('index')}" for s in ET.parse(QURAN_XML).getroot().iter("sura") for a in s.iter("aya")]
    assert len(refs) == 6236, f"expected 6236 ayahs in {QURAN_XML}, found {len(refs)}"
    return refs


def get(url):
    """The URL's JSON; ATTEMPTS tries, 2 s * attempt apart."""
    last = None
    for attempt in range(1, ATTEMPTS + 1):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (hafiz tools/mushaf_layout.py)"})
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.load(r)
        except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as e:
            last = e
            if attempt < ATTEMPTS:
                time.sleep(2 * attempt)
    raise RuntimeError(f"{url}: {last}")


def fetch_page(page):
    """[(verse_key, v1_page, line_v1, v2_page, line_v2)] of the ayahs listed on `page` (their first word's position)."""
    out = []
    n = 1
    while n:
        data = get(URL.format(page, n))
        for v in data["verses"]:
            first = v["words"][0]
            out.append((v["verse_key"], first["v1_page"], first["line_v1"], first["v2_page"], first["line_v2"]))
        n = data.get("pagination", {}).get("next_page")
    return out


def validate(edition, where, refs):
    """Exits unless `where` (ayah -> (page, line)) is a complete, in-range, non-decreasing layout of `refs`."""
    if set(where) != set(refs):
        missing, extra = sorted(set(refs) - set(where)), sorted(set(where) - set(refs))
        sys.exit(f"{edition}: ayah set differs from Tanzil: missing {missing[:5]}, unexpected {extra[:5]}")
    previous = 0
    for ref in refs:
        page, line = where[ref]
        if not (isinstance(page, int) and isinstance(line, int)):
            sys.exit(f"{edition} {ref}: page {page!r}, line {line!r} is not a number")
        if not 1 <= page <= PAGES or not 1 <= line <= LINES:
            sys.exit(f"{edition} {ref}: page {page}, line {line} out of range")
        if page < previous:
            sys.exit(f"{edition} {ref}: page {page} is before the previous ayah's page {previous}")
        previous = page


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    out_dir = parser.parse_args().out_dir
    refs = load_refs()
    try:
        with ThreadPoolExecutor(8) as pool:
            fetched = list(pool.map(fetch_page, range(1, PAGES + 1)))
    except (RuntimeError, KeyError) as e:
        sys.exit(f"fetch failed: {e!r}")
    where = {edition: {} for edition in EDITIONS}
    for rows in fetched:
        for key, v1_page, v1_line, v2_page, v2_line in rows:
            if key in where["v1"]:
                sys.exit(f"duplicate ayah {key}")
            where["v1"][key] = (v1_page, v1_line)
            where["v2"][key] = (v2_page, v2_line)
    for edition in EDITIONS:
        validate(edition, where[edition], refs)
    out_dir.mkdir(parents=True, exist_ok=True)
    for edition, (print_, fields) in EDITIONS.items():
        path = out_dir / f"mushaf_layout_{edition}.txt"
        body = "".join(f"{ref} {where[edition][ref][0]} {where[edition][ref][1]}\n" for ref in refs)
        path.write_text(HEADER.format(print=print_, fields=fields) + body, encoding="utf-8")
        cells = Counter((page % 2 == 1, (line - 1) // 5) for page, line in where[edition].values() if page > 2)
        print(f"wrote {len(refs)} ayahs to {path}")
        for right in (True, False):
            for third, name in enumerate(("top", "middle", "bottom")):
                print(f"  {edition}: {'right' if right else 'left':5} {name:6} {cells[(right, third)]}")


if __name__ == "__main__":
    main()
